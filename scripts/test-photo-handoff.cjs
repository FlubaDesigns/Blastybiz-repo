// Exercise the real review controls with native sharing/clipboard boundaries stubbed.
'use strict';
const {JSDOM}=require(process.env.JSDOM_PATH||'jsdom');
const fs=require('node:fs'),assert=require('node:assert/strict');
const dom=new JSDOM('<!doctype html><body><div id="step5-review-container"></div>',{url:'https://example.com',runScripts:'outside-only'});
const w=dom.window,html=fs.readFileSync('public/BlastyBiz.html','utf8');
let calls=[],fetches=[],downloads=[],clipboard=[],notices=[],shareError=null,failUrl='',supported=true,checks=0;
const ok=(value,message)=>{assert(value,message);checks++;};
const tick=async()=>{for(let i=0;i<10;i++)await new Promise(r=>setImmediate(r));};
w.fetch=async url=>{fetches.push(url);return {ok:url!==failUrl,blob:async()=>new w.Blob(['bytes:'+url],{type:'image/png'})};};
w.navigator.canShare=()=>supported;
w.navigator.share=data=>{calls.push(data);return shareError?Promise.reject(shareError):Promise.resolve();};
Object.defineProperty(w.navigator,'clipboard',{value:{write:async items=>{clipboard.push(await items[0].data['image/png']);}}});
w.ClipboardItem=class{constructor(data){this.data=data;}};
w.URL.createObjectURL=()=> 'blob:prepared-photo';w.URL.revokeObjectURL=()=>{};
w.HTMLAnchorElement.prototype.click=function(){downloads.push({href:this.href,name:this.download});};
const nativeTimer=w.setTimeout.bind(w);w.setTimeout=(fn,ms)=>ms===60000?0:nativeTimer(fn,ms);
Object.assign(w,{showToast:v=>notices.push(v),_step5PlatIdx:0,updateStep5UI(){},_bbIsGenerating:()=>false,PLATFORM_URL_HINTS:{},escHtml:s=>String(s).replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;')});
w.eval(fs.readFileSync('public/platforms-authority.js','utf8'));w.eval(fs.readFileSync('public/photo-handoff.js','utf8'));
w.eval(html.slice(html.indexOf('function renderPlatformPhotoStrip('),html.indexOf('// Open a platform page')));
w.eval(html.slice(html.indexOf('function renderStep5Review()'),html.indexOf('function updateStep5UI()')));
const photos=Array.from({length:6},(_,i)=>({id:'p'+i,url:'https://example.com/photo'+i+'.png'}));
w.BBAds={active:{imageRefs:photos,platformStatus:{x:'approved'}}};
w.platforms=[{id:'x',name:'X',type:'manual',adaptedContent:'Saved caption',enabled:true}];w.getStep5Platforms=()=>w.platforms;
const button=()=>w.document.querySelector('#qp-share-x button');
const read=file=>new Promise((resolve,reject)=>{const r=new w.FileReader();r.onload=()=>resolve(r.result);r.onerror=reject;r.readAsText(file);});
(async()=>{
 w.renderStep5Review();ok(button().disabled,'sharing waits for real image files');await tick();
 ok(calls.length===0&&downloads.length===0,'review never opens a share sheet or downloads automatically');
 ok(button().textContent==='Share 4 photos'&&!button().disabled,'X ready button uses the four visible photos');
 ok(fetches.length===4,'downloads only the included photos');
 w.document.getElementById('qp-copy-text-x').textContent='Edited caption';button().click();
 ok(calls.length===1,'native share starts synchronously inside the ready button click');await tick();
 ok(calls[0].files.length===4&&calls[0].text==='Edited caption','share contains current caption and exact photo allowance');
 ok(await read(calls[0].files[2])==='bytes:'+photos[2].url,'shares image bytes, not URLs or substituted text');
 ok(calls[0].files[2].name==='blastybiz-x-3.png','shared photos have recognizable filenames');
 ok(w.BBAds.active.platformStatus.x==='approved','handoff never changes approval or marks a post delivered');
 w.document.querySelector('.qp-photo-tools button').click();await tick();
 ok(clipboard.length===1&&clipboard[0].type==='image/png','visible Copy photo sends image data to clipboard');
 w.document.querySelectorAll('.qp-photo-tools button')[1].click();await tick();
 ok(downloads[0].href==='blob:prepared-photo'&&downloads[0].name==='blastybiz-x-1.png','Save photo downloads the exact image with a clear filename');
 ok(fetches.length===4,'sharing/copy/save reuse prepared files');
 shareError=Object.assign(new Error('Canceled'),{name:'AbortError'});button().click();await tick();
 ok(calls.length===2&&!button().disabled,'cancel returns control without opening a second text-only share');shareError=null;
 supported=false;w.renderStep5Review();await tick();
 ok(button().hidden&&w.document.querySelectorAll('.qp-photo-tools button').length===8,'unsupported file sharing exposes copy/save fallbacks');
 supported=true;failUrl='https://example.com/retry.png';w.BBAds.active.imageRefs=[{url:failUrl}];w.renderStep5Review();await tick();
 ok(button().textContent==='Retry preparing photos'&&!button().disabled,'failed photo fetch gives a retry instead of sharing text alone');
 const previousShares=calls.length;failUrl='';button().click();await tick();
 ok(calls.length===previousShares&&button().textContent==='Share 1 photo','retry prepares successfully and waits for a fresh share gesture');
 button().click();await tick();ok(calls.at(-1).files.length===1,'retry hands off the newly selected photo');
 w.BBAds.active.imageRefs=[];w.renderStep5Review();await tick();ok(!button(),'empty selections have no misleading share button');
 console.log('PASS: '+checks+' photo handoff assertions.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>dom.window.close());
